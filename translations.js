function changeLanguage(lang) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
    
    // Update labels and text
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === 'SPAN' || el.tagName === 'A' || el.tagName === 'P' || el.tagName === 'H2' || el.tagName === 'H3' || el.tagName === 'H4' || el.tagName === 'OPTION' || el.tagName === 'LI') {
                el.textContent = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });

    // Update input placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    // Toggle button adjustments
    const toggleBtn = document.getElementById('langToggle');
    if (toggleBtn) {
        if (lang === 'en') {
            toggleBtn.innerHTML = '<i class="fas fa-globe"></i> AR';
            toggleBtn.setAttribute('data-target-lang', 'ar');
        } else {
            toggleBtn.innerHTML = '<i class="fas fa-globe"></i> EN';
            toggleBtn.setAttribute('data-target-lang', 'en');
        }
    }

    // Call sliding logic if custom render function exists
    if (typeof window.renderPartners === 'function') {
        window.renderPartners();
    }
    
    // Call projects re-render if function exists
    if (typeof window.initializeGallery === 'function') {
        const galleryContainer = document.getElementById('projects-container');
        if (galleryContainer && galleryContainer.innerHTML !== '') {
            const activeFilterBtn = document.querySelector('.filter-btn.active');
            const filter = activeFilterBtn ? activeFilterBtn.dataset.filter : 'all';
            if (typeof window.filterProjects === 'function') {
                window.filterProjects(filter);
            }
        }
    }
    
    // Save to local storage
    localStorage.setItem('preferredLang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
    const toggleBtn = document.getElementById('langToggle');
    if (toggleBtn) {
        toggleBtn.addEventListener('click', () => {
            const targetLang = toggleBtn.getAttribute('data-target-lang') || 'en';
            changeLanguage(targetLang);
        });
    }

    // Load saved language
    const savedLang = localStorage.getItem('preferredLang') || 'ar';
    if (savedLang === 'en') {
        setTimeout(() => changeLanguage('en'), 100);
    }
});
